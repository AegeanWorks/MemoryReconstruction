#!/usr/bin/env python3
"""Generate the cumulative commit-range inventory used by the audit.

The audit walks `1 -> 3`, `1 -> 6`, `1 -> 9`, ... through `1 -> End`.
This script lists every range, the three commits added by it, the repository
file count at its endpoint, and whether `docs/COMMIT_RANGE_AUDIT.md` contains a
narrative deep dive for it. It is read-only apart from writing the inventory
file (or checking it with `--check`).

A tracked inventory generated at HEAD always lags the commit that contains it.
To avoid that self-reference, the latest commit touching the inventory is
omitted from the range list when it changes only audit/governance files (the
curated report, the inventory, this script or `.aikit/`). Content commits still
shift `1 -> End` and require a refresh.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / "docs" / "COMMIT_RANGE_AUDIT.md"
DEFAULT_OUTPUT = ROOT / "docs" / "COMMIT_RANGE_INVENTORY.md"
STEP = 3
AUDIT_ONLY_PATHS = {
    "docs/COMMIT_RANGE_AUDIT.md",
    "docs/COMMIT_RANGE_INVENTORY.md",
    "scripts/audit_commit_ranges.py",
}


def git(*args: str) -> str:
    """Run a git command in the project root with a hard timeout."""
    result = subprocess.run(
        ["git", *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {result.stderr.strip()}")
    return result.stdout


def last_inventory_commit() -> str:
    """Full hash of the latest commit touching the generated inventory."""
    return git("log", "-1", "--format=%H", "--", "docs/COMMIT_RANGE_INVENTORY.md").strip()


def is_audit_only(commit: str) -> bool:
    """True when a commit changes only the audit report, inventory, script or memory."""
    files = [
        line.strip()
        for line in git("show", "--pretty=format:", "--name-only", commit).splitlines()
        if line.strip()
    ]
    return bool(files) and all(
        path in AUDIT_ONLY_PATHS or path.startswith(".aikit/") for path in files
    )


def commit_rows() -> list[tuple[str, str]]:
    """Return `(short hash, subject)` for every content commit, oldest first."""
    raw = git("log", "--reverse", "--format=%h%x09%H%x09%s")
    refresh = last_inventory_commit()
    skip = refresh if refresh and is_audit_only(refresh) else ""
    rows: list[tuple[str, str]] = []
    for line in raw.splitlines():
        if not line.strip():
            continue
        short, full, subject = line.split("\t", 2)
        if full == skip:
            continue
        rows.append((short, subject))
    return rows


def deep_dive_ranges() -> set[int]:
    """Ranges with a narrative section in the curated audit report."""
    if not AUDIT.exists():
        return set()
    text = AUDIT.read_text(encoding="utf-8")
    return {int(match.group(1)) for match in re.finditer(r"^## Range 1 -> (\d+)", text, re.M)}


def build_inventory() -> str:
    rows = commit_rows()
    if not rows:
        raise RuntimeError("the repository has no commits")
    deep = deep_dive_ranges()
    lines = [
        "# Commit-Range Inventory",
        "",
        "Generated by `scripts/audit_commit_ranges.py`; do not hand-edit. The",
        "curated findings live in `docs/COMMIT_RANGE_AUDIT.md`. Every row is a",
        "cumulative range from commit 1, in steps of three, ending at `1 -> End`.",
        "",
        "| Range | End commit | New commits | Files at end | Deep dive |",
        "| --- | --- | --- | --- | --- |",
    ]
    total = len(rows)
    for end in range(STEP, total + 1, STEP):
        added = rows[end - STEP : end]
        end_hash, _ = rows[end - 1]
        files = len(git("ls-tree", "-r", "--name-only", end_hash).splitlines())
        subjects = "<br>".join(f"`{short}` {subject.replace('|', '\\|')}" for short, subject in added)
        lines.append(
            f"| 1 -> {end} | `{end_hash}` | {subjects} | {files} | {'yes' if end in deep else ''} |"
        )
    if total % STEP:
        end = total
        added = rows[end - (end % STEP) : end]
        end_hash, _ = rows[end - 1]
        files = len(git("ls-tree", "-r", "--name-only", end_hash).splitlines())
        subjects = "<br>".join(f"`{short}` {subject.replace('|', '\\|')}" for short, subject in added)
        lines.append(
            f"| 1 -> {end} (End) | `{end_hash}` | {subjects} | {files} | {'yes' if end in deep else ''} |"
        )
    lines.extend(
        [
            "",
            "The deep-dive column marks ranges with a narrative section in the",
            "curated report. The current tree is verified by the full suite in",
            "the report's Current gates section and by the audit's targeted tests.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail if the inventory is stale")
    args = parser.parse_args()
    content = build_inventory()
    if args.check:
        existing = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if existing != content:
            print(f"[STALE] {args.output} does not match the commit history")
            return 1
        print(f"[OK] {args.output} is current")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"[OK] wrote {args.output}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (RuntimeError, subprocess.TimeoutExpired) as exc:
        print(f"Why: {exc}", file=sys.stderr)
        print("Fix: run from the project root with git available on PATH.", file=sys.stderr)
        raise SystemExit(1)
